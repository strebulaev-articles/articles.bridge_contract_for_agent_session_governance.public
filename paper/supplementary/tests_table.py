#!/usr/bin/env python3
"""Generate and check the paper's tests table (tab:tests).

The test IDs are read from conformance_suite.py (function names test_T<n>[a-z]
in file order); the prose per row lives in tests_table_rows.py. The check fails
when a row names a test the suite does not have, when a test in the suite is in
no row, or when the committed paper/sections/generated_tests.tex is stale.

    python3 -I tests_table.py --emit-tex ../sections/generated_tests.tex
    python3 -I tests_table.py --check-paper ../sections/generated_tests.tex
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from tests_table_rows import ROWS  # noqa: E402

ID = r"T\d+[a-z]?"


def suite_ids() -> list[str]:
    src = (HERE / "conformance_suite.py").read_text()
    seen: list[str] = []
    for m in re.finditer(rf"^def test_({ID})(?=_|\()", src, re.M):
        if m.group(1) not in seen:
            seen.append(m.group(1))
    return seen


def expand(label: str, order: list[str]) -> tuple[set[str], list[str]]:
    label = re.sub(r"\([^)]*\)", "", label)
    ids: set[str] = set()
    errs: list[str] = []
    for part in (p.strip() for p in label.split(",") if p.strip()):
        m = re.fullmatch(rf"({ID})(?:--({ID}))?", part)
        if not m:
            errs.append(f"unreadable test label {part!r}")
            continue
        lo, hi = m.group(1), m.group(2) or m.group(1)
        if lo not in order or hi not in order:
            errs.append(f"row names a test the suite lacks: {part}")
            continue
        ids.update(order[order.index(lo):order.index(hi) + 1])
    return ids, errs


def problems() -> list[str]:
    order = suite_ids()
    covered: set[str] = set()
    errs: list[str] = []
    for tests, _inv, _text in ROWS:
        got, e = expand(tests, order)
        covered |= got
        errs += e
    errs += [f"test {t} is in no row of the table" for t in order
             if t not in covered]
    return errs


def emit_tex() -> str:
    head = ("% GENERATED by supplementary/tests_table.py --emit-tex; "
            "do not edit.\n"
            "\\begin{longtable}{p{0.12\\columnwidth} p{0.2\\columnwidth} "
            "p{0.58\\columnwidth}}\n"
            "\\caption{Tests and the invariants they exercise.}"
            "\\label{tab:tests}\\\\\n"
            "\\toprule\n"
            "\\textbf{Tests} & \\textbf{Invariants} & "
            "\\textbf{What they check} \\\\\n\\midrule\n")
    rows = "".join(f"{a} & {b} &\n{c} \\\\\n" for a, b, c in ROWS)
    return head + rows + "\\bottomrule\n\\end{longtable}\n"


def check_paper(path: Path) -> list[str]:
    errs = problems()
    if not path.exists() or path.read_text() != emit_tex():
        errs.append(f"{path} is stale; run tests_table.py --emit-tex {path}")
    return errs


def main(argv: list[str]) -> int:
    if "--emit-tex" in argv:
        errs = problems()
        for m in errs:
            print("FAIL", m)
        if errs:
            return 1
        Path(argv[argv.index("--emit-tex") + 1]).write_text(emit_tex())
        return 0
    if "--check-paper" in argv:
        errs = check_paper(Path(argv[argv.index("--check-paper") + 1]))
        for m in errs:
            print("FAIL", m)
        return 1 if errs else 0
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
